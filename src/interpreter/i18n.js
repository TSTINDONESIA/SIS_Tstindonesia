const KEY = 'tst-lang';
export function initLang() {
  try { const s = localStorage.getItem(KEY); if (s === 'id' || s === 'en') return s; } catch { /* */ }
  return (navigator.language || 'id').toLowerCase().startsWith('id') ? 'id' : 'en';
}
export function saveLang(l) { try { localStorage.setItem(KEY, l); } catch { /* */ } }
